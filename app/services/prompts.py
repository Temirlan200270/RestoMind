def _pricing_suffix() -> str:
    """Динамические пороги из .env (ТЗ v2)."""
    from app.core.config import settings

    return (
        "\n\n# Параметры ТЗ (из настроек сервера)\n"
        f"- Доставка: **{int(settings.pricing_delivery_fee)}** ₸ при сумме блюд до **{int(settings.pricing_delivery_free_threshold)}** ₸; "
        "выше порога — бесплатная доставка.\n"
        f"- Предоплата за бронь в зале — минимум **{settings.hall_prepayment_min}** ₸ (в счёт визита).\n"
        f"- Заказ от **{int(settings.order_prepayment_threshold_kzt):,}** ₸ и выше: требуется **предоплата заказа**; "
        "клиент не сможет подтвердить «Да», пока оператор не отметит оплату.\n"
        "- **Упаковка** (контейнеры добавляются автоматически при доставке/самовывозе):\n"
        f"  • Стандартный ланч-бокс: **{int(settings.packaging_standard_unit_price)}** ₸/порция\n"
        f"  • Манты: **{int(settings.packaging_manty_unit_price)}** ₸/порция\n"
        f"  • Шашлык: **{int(settings.packaging_shashlik_unit_price)}** ₸/порция\n"
        f"  • Фри (соусница): **{int(settings.packaging_fries_unit_price)}** ₸/порция\n"
        f"  • Плов 0.5: **{int(settings.packaging_plov_half_unit_price)}** ₸/порция\n"
        f"  • Плов 1 кг: **табак {int(settings.packaging_plov_1kg_tabak_unit_price)}** ₸ или **казан {int(settings.packaging_plov_1kg_foil_unit_price)}** ₸/порция (выбор клиента)\n"
        "- В зале контейнеры **не начисляются**.\n"
    )


def _menu_public_url_suffix() -> str:
    """Ссылка на онлайн-меню для клиентов (из .env)."""
    from app.core.config import settings

    u = (settings.menu_public_url or "").strip()
    if not u:
        return ""
    return (
        "\n\n# Публичное меню (ссылка для клиента)\n"
        f"Если клиент просит **меню**, «где посмотреть блюда», каталог, сайт или ссылку на цены — "
        f"ответь с `intent=faq` и в `reply_text` дай **только эту** ссылку (можно одной строкой с коротким пояснением): {u}\n"
        f"Не выдумывай другие URL и не подставляй адреса из головы.\n"
    )


RESTAURANT_SYSTEM_PROMPT = _RESTAURANT_SYSTEM_PROMPT_RAW + _pricing_suffix() + _menu_public_url_suffix()
