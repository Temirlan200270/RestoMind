def _pricing_suffix() -> str:
    """Динамические пороги из .env (ТЗ v2)."""
    from app.core.config import settings

    return (
        "\n\n# Параметры ТЗ (из настроек сервера)\n"
        f"- Доставка: **{int(settings.pricing_delivery_fee)}** ₸ при сумме блюд до **{int(settings.pricing_delivery_free_threshold)}** ₸; "
        "выше порога — без отдельной платы за доставку.\n"
        f"- Предоплата за бронь в зале — минимум **{settings.hall_prepayment_min}** ₸ (в счёт визита).\n"
        f"- Заказ от **{int(settings.order_prepayment_threshold_kzt):,}** ₸ и выше: требуется **предоплата заказа**; "
        "клиент не сможет подтвердить «Да», пока оператор не отметит оплату.\n"
        f"- Упаковка: манты **{int(settings.packaging_manty_unit_price)}** ₸/порция; плов 0.5 — **{int(settings.packaging_plov_half_unit_price)}** ₸/порция; "
        f"плов 1 кг — **табак {int(settings.packaging_plov_1kg_tabak_unit_price)}** ₸ или **казан {int(settings.packaging_plov_1kg_foil_unit_price)}** ₸/порция (выбор клиента).\n"
    )


RESTAURANT_SYSTEM_PROMPT = _RESTAURANT_SYSTEM_PROMPT_RAW + _pricing_suffix()
